class TestOrchestrateDryRun:
    @pytest.mark.asyncio
    async def test_full_pipeline(self, orchestrator):
        result = await orchestrator.orchestrate(
            query=QUERY, sets=3, per_set=6, interface="gemini", mode="auto"
        )

        expected_keys = {
            "query", "sets", "per_set", "interface", "mode_used",
            "decomposition", "set_results", "report_markdown",
            "report_path", "references",
        }
        assert expected_keys <= set(result.keys())
        assert result["mode_used"] == "heuristic"

        assert len(result["set_results"]) == 3
        for sr in result["set_results"]:
            assert set(sr.keys()) == {"set_index", "lens", "research_output", "consolidated"}
            assert sr["research_output"]["metadata"]["dry_run"] is True

        md = result["report_markdown"]
        assert md.startswith(f"# Deep Research Report: {QUERY}")
        assert "## Executive Summary" in md
        assert "## References" in md
        for lens in [d["lens"] for d in result["decomposition"]]:
            assert lens in md
        assert "Generated by DataKiln Research Orchestrator" in md
        assert "No external references captured in dry-run mode" in md
        assert result["references"] == []

        report_path = Path(result["report_path"])
        assert report_path.exists()
        content = report_path.read_text(encoding="utf-8")
        assert len(content) > 500
        assert content == md

    @pytest.mark.asyncio
    async def test_failed_set_does_not_abort_others(self, monkeypatch, tmp_path):
        def exploding(set_index, query):
            if set_index == 1:
                raise RuntimeError("boom")
            return {
                "result": f"[dry-run:dom.gemini.deep_research] {query}",
                "actions": [],
                "metadata": {"dry_run": True, "set_index": set_index},
            }

        monkeypatch.setattr(
            orch_mod.ResearchOrchestrator, "_dry_run_research", staticmethod(exploding)
        )
        orchestrator = ResearchOrchestrator(reports_dir=tmp_path)
        result = await orchestrator.orchestrate(query="x topic", sets=3, per_set=2)

        failed = next(sr for sr in result["set_results"] if sr["set_index"] == 1)
        ok = next(sr for sr in result["set_results"] if sr["set_index"] == 2)
        assert "error" in failed["research_output"]
        assert failed["consolidated"] == ""
        assert "error" not in ok["research_output"]
        assert ok["consolidated"]

    @pytest.mark.asyncio
    async def test_references_collected_from_outputs(self, monkeypatch, tmp_path):
        def with_url(set_index, query):
            return {
                "result": f"Findings from https://example.com/source-{set_index} about {query}.",
                "actions": [],
                "metadata": {"dry_run": True},
            }

        monkeypatch.setattr(
            orch_mod.ResearchOrchestrator, "_dry_run_research", staticmethod(with_url)
        )
        orchestrator = ResearchOrchestrator(reports_dir=tmp_path)
        result = await orchestrator.orchestrate(query=QUERY, sets=2, per_set=2)
        assert sorted(result["references"]) == [
            "https://example.com/source-0",
            "https://example.com/source-1",
        ]
        assert "## References" in result["report_markdown"]
        assert "https://example.com/source-0" in result["report_markdown"]


