class TestDecomposition:
    @pytest.mark.asyncio
    async def test_lens_count_and_rotation(self, orchestrator):
        decomposition = orchestrator._heuristic_decompose(QUERY, sets=5, per_set=6)
        assert len(decomposition) == 5
        lenses = [d["lens"] for d in decomposition]
        assert len(set(lenses)) == 5  # unique within a run
        assert lenses == [LENSES[i % len(LENSES)] for i in range(5)]  # rotating order

    @pytest.mark.asyncio
    async def test_rotation_wraps_past_eight_sets(self, orchestrator):
        decomposition = orchestrator._heuristic_decompose(QUERY, sets=8, per_set=1)
        assert len({d["lens"] for d in decomposition}) == 8
        assert decomposition[0]["lens"] == LENSES[0]
        assert decomposition[7]["lens"] == LENSES[7]

    @pytest.mark.asyncio
    async def test_per_set_question_counts(self, orchestrator):
        decomposition = orchestrator._heuristic_decompose(QUERY, sets=3, per_set=6)
        for d in decomposition:
            assert len(d["questions"]) == 6
            assert all(q.endswith("?") for q in d["questions"])

    @pytest.mark.asyncio
    async def test_questions_contain_query_and_lens(self, orchestrator):
        decomposition = orchestrator._heuristic_decompose(QUERY, sets=3, per_set=6)
        for d in decomposition:
            for q in d["questions"]:
                assert QUERY in q
                assert q.startswith(f"{d['lens']}:")

    @pytest.mark.asyncio
    async def test_decompose_falls_back_to_heuristic_without_key(self, orchestrator):
        decomposition, mode_used = await orchestrator._decompose(QUERY, 3, 6)
        assert mode_used == "heuristic"
        assert len(decomposition) == 3


