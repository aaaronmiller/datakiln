class TestOrchestrateEndpoints:
    def test_post_orchestrate_default_params(self, client):
        resp = client.post("/api/v1/research/orchestrate", json={"query": QUERY})
        assert resp.status_code == 200
        body = resp.json()
        for key in (
            "query", "sets", "per_set", "interface", "mode_used",
            "decomposition", "set_results", "report_markdown",
            "report_path", "references",
        ):
            assert key in body
        assert body["sets"] == 3
        assert body["per_set"] == 6
        assert body["query"] == QUERY
        assert body["mode_used"] == "heuristic"
        assert len(body["set_results"]) == 3
        assert Path(body["report_path"]).exists()

    def test_post_orchestrate_custom_params(self, client):
        resp = client.post(
            "/api/v1/research/orchestrate",
            json={"query": "quantum computing", "sets": 2, "per_set": 4},
        )
        assert resp.status_code == 200
        body = resp.json()
        assert body["sets"] == 2 and body["per_set"] == 4
        assert len(body["decomposition"]) == 2

    def test_post_orchestrate_validation_bounds(self, client):
        resp = client.post("/api/v1/research/orchestrate", json={"query": "q", "sets": 9})
        assert resp.status_code == 422
        resp = client.post("/api/v1/research/orchestrate", json={"query": "q", "sets": 0})
        assert resp.status_code == 422
        resp = client.post("/api/v1/research/orchestrate", json={"query": "q", "per_set": 13})
        assert resp.status_code == 422
        resp = client.post("/api/v1/research/orchestrate", json={"query": "q"})
        assert resp.status_code == 200

    def test_get_reports_listing(self, client):
        client.post("/api/v1/research/orchestrate", json={"query": "listing test"})
        resp = client.get("/api/v1/research/orchestrate/reports")
        assert resp.status_code == 200
        reports = resp.json()["reports"]
        assert isinstance(reports, list) and len(reports) >= 1
        for entry in reports:
            assert set(entry.keys()) == {"file", "path", "size", "modified"}
